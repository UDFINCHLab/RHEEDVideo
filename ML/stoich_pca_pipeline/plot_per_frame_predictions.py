"""
Generate per-video prediction-over-time plots and a grid overview.

Edit DATASET_NAME below to switch datasets.

Reads gated_cnn_cluster_filtered_per_frame.csv and produces:
  - per_frame_plots/individual_plots/<sample>.png  (one plot per video)
  - per_frame_plots/grid_all_videos.png            (grid sorted by target value)

Each plot:
  - Blue dots: per-frame predictions for frames the CNN was trained on
  - Gray dots: per-frame predictions for frames OUTSIDE the training filter
  - Red line:  actual target value (ground truth)
  - Green dashed line: mean prediction over training-filter frames
"""

from pathlib import Path
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent


# -----------------------------
# DATASET SELECTION — edit this to switch datasets
# -----------------------------
DATASET_NAME = "CSO"   # "STO" or "CSO"


# -----------------------------
# PATHS — derived automatically from DATASET_NAME
# -----------------------------
# PER_FRAME_CSV: per-frame predictions generated by train_gated_cnn_final.py
# OUTPUT_DIR:    plots saved under results/{DATASET_NAME}/gated_cnn/per_frame_plots/
PER_FRAME_CSV = (PROJECT_ROOT / "results" / DATASET_NAME
                 / "gated_cnn_cluster_filtered"
                 / "gated_cnn_cluster_filtered_per_frame.csv")
OUTPUT_DIR    = (PROJECT_ROOT / "results" / DATASET_NAME
                 / "gated_cnn_cluster_filtered"
                 / "per_frame_plots")


def plot_single_video(sub, sid, actual, save_path, y_range, target_label):
    """
    Generate and save a per-frame prediction plot for one video.
    Blue dots = training-filter frames.
    Gray dots = excluded frames (other clusters).
    Red line  = actual target ground truth.
    Green dashed line = mean prediction over training-filter frames.
    Green shaded band = +/- 1 standard deviation.
    """
    fig, ax = plt.subplots(figsize=(11, 5))

    in_filter  = sub[sub["in_training_filter"] == True]
    out_filter = sub[sub["in_training_filter"] == False]

    if len(out_filter) > 0:
        ax.scatter(out_filter["frame_idx_in_video"], out_filter["predicted_xps"],
                   s=10, c="gray", alpha=0.3,
                   label=f"Out-of-filter frames ({len(out_filter)})")

    ax.scatter(in_filter["frame_idx_in_video"], in_filter["predicted_xps"],
               s=14, c="#185FA5", alpha=0.7,
               label=f"Training-filter frames ({len(in_filter)})")

    ax.axhline(actual, color="red", linewidth=2, linestyle="-",
               label=f"Actual {target_label} = {actual:.4f}")

    mean_pred = (in_filter["predicted_xps"].mean() if len(in_filter) > 0
                 else sub["predicted_xps"].mean())
    ax.axhline(mean_pred, color="green", linewidth=1.5, linestyle="--",
               label=f"Mean filter pred = {mean_pred:.4f}")

    std_pred = (in_filter["predicted_xps"].std() if len(in_filter) > 0
                else sub["predicted_xps"].std())
    ax.axhspan(mean_pred - std_pred, mean_pred + std_pred,
               color="green", alpha=0.1, label=f"+/- 1 std ({std_pred:.4f})")

    err = abs(mean_pred - actual)
    ax.set_xlabel("Frame index in video", fontweight="bold")
    ax.set_ylabel(f"Predicted {target_label}", fontweight="bold")
    ax.set_title(f"[{DATASET_NAME}] {sid}  "
                 f"(actual={actual:.4f}, predicted={mean_pred:.4f}, "
                 f"err={err:.4f}, total={len(sub)} frames)",
                 fontweight="bold")
    ax.set_ylim(y_range)
    ax.grid(True, alpha=0.3)
    ax.legend(loc="best", fontsize=9)

    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches="tight")
    plt.close()


def plot_grid(pf_df, save_path, target_label, n_videos):
    """
    Generate a compact grid overview of per-frame predictions for all videos,
    sorted by target value. Each panel shows blue/gray dots,
    red actual target line, and green mean prediction line.
    """
    sorted_sids = (pf_df.groupby("sample_id")["actual_xps"]
                   .first().sort_values().index.tolist())

    n_cols = min(5, n_videos)
    n_rows = int(np.ceil(n_videos / n_cols))

    y_lo = min(pf_df["actual_xps"].min(), pf_df["predicted_xps"].min()) - 0.5
    y_hi = max(pf_df["actual_xps"].max(), pf_df["predicted_xps"].max()) + 0.5

    fig, axes = plt.subplots(n_rows, n_cols,
                             figsize=(4 * n_cols, 3 * n_rows), sharey=True)
    axes = np.array(axes).flatten()

    fig.suptitle(f"[{DATASET_NAME}] Per-frame CNN predictions (sorted by {target_label})",
                 fontsize=14, fontweight="bold", y=0.998)

    for i, sid in enumerate(sorted_sids):
        ax  = axes[i]
        sub = pf_df[pf_df["sample_id"] == sid].sort_values("frame_idx_in_video")
        actual = float(sub["actual_xps"].iloc[0])

        in_filter  = sub[sub["in_training_filter"] == True]
        out_filter = sub[sub["in_training_filter"] == False]

        if len(out_filter) > 0:
            ax.scatter(out_filter["frame_idx_in_video"], out_filter["predicted_xps"],
                       s=3, c="gray", alpha=0.3)
        ax.scatter(in_filter["frame_idx_in_video"], in_filter["predicted_xps"],
                   s=4, c="#185FA5", alpha=0.7)

        mean_pred = (in_filter["predicted_xps"].mean() if len(in_filter) > 0
                     else sub["predicted_xps"].mean())
        ax.axhline(actual,    color="red",   linewidth=1.2)
        ax.axhline(mean_pred, color="green", linewidth=0.9, linestyle="--")

        err = abs(mean_pred - actual)
        ax.set_title(f"{sid}\nact={actual:.3f} pred={mean_pred:.3f} err={err:.3f}",
                     fontsize=8, fontweight="bold")
        ax.set_ylim(y_lo, y_hi)
        ax.grid(True, alpha=0.3)
        ax.tick_params(axis="both", labelsize=7)

    for j in range(n_videos, len(axes)):
        fig.delaxes(axes[j])

    fig.text(0.5, 0.005, "Frame index in video",
             ha="center", fontsize=11, fontweight="bold")
    fig.text(0.005, 0.5, f"Predicted {target_label}",
             va="center", rotation="vertical", fontsize=11, fontweight="bold")

    plt.tight_layout(rect=[0.015, 0.015, 1, 0.99])
    plt.savefig(save_path, dpi=150, bbox_inches="tight")
    plt.close()


def main():
    """
    Load the per-frame predictions CSV, generate individual plots for each video,
    then generate the combined grid overview.
    Y-axis range is shared across all plots for visual comparability.
    Raises FileNotFoundError if train_gated_cnn_final.py has not been run yet.
    """
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    individual_dir = OUTPUT_DIR / "individual_plots"
    individual_dir.mkdir(parents=True, exist_ok=True)

    if not PER_FRAME_CSV.exists():
        raise FileNotFoundError(f"Not found: {PER_FRAME_CSV}\n"
                                f"Run train_gated_cnn_final.py first.")

    pf_df = pd.read_csv(str(PER_FRAME_CSV))
    print(f"Dataset: {DATASET_NAME}")
    print(f"Loaded {len(pf_df)} per-frame predictions")
    print(f"Unique samples: {pf_df['sample_id'].nunique()}")

    # Use "2-theta" label for CSO, "XPS" for STO
    target_label = "2-theta" if DATASET_NAME == "CSO" else "XPS"
    print(f"Target label: {target_label}")
    print(f"Target range: {pf_df['actual_xps'].min():.4f} - {pf_df['actual_xps'].max():.4f}\n")

    y_lo    = min(pf_df["actual_xps"].min(), pf_df["predicted_xps"].min()) - 0.5
    y_hi    = max(pf_df["actual_xps"].max(), pf_df["predicted_xps"].max()) + 0.5
    y_range = (y_lo, y_hi)

    sample_ids = pf_df["sample_id"].unique()
    print("Generating individual per-video plots...")
    for sid in sample_ids:
        sub    = pf_df[pf_df["sample_id"] == sid].sort_values("frame_idx_in_video")
        actual = float(sub["actual_xps"].iloc[0])
        safe   = sid.replace("=", "_eq_").replace(" ", "_")
        plot_single_video(sub, sid, actual,
                          individual_dir / f"{safe}.png",
                          y_range, target_label)
        print(f"  {sid}")

    print(f"\nGenerating grid plot of all {len(sample_ids)} videos...")
    grid_path = OUTPUT_DIR / f"grid_all_{len(sample_ids)}_videos.png"
    plot_grid(pf_df, grid_path, target_label, len(sample_ids))
    print(f"Saved grid: {grid_path}")

    print(f"\nDone.")
    print(f"  Individual plots: {individual_dir}")
    print(f"  Grid plot:        {grid_path}")


if __name__ == "__main__":
    main()